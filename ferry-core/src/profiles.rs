use crate::{yaml_dq, GenerateInput};
use serde::{Deserialize, Serialize};
use serde_yaml::Value;
use std::collections::{HashMap, HashSet};

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum ConfigTarget {
    #[default]
    Pc,
    // Keep the serialized legacy key "nikki" so saved browser drafts remain compatible.
    Nikki,
}

impl ConfigTarget {
    pub fn file_label(self) -> &'static str {
        match self {
            Self::Pc => "Desktop",
            Self::Nikki => "Router",
        }
    }
}

pub fn instructions(input: &GenerateInput) -> String {
    let target = match input.target {
        ConfigTarget::Pc => "电脑版：适用于 Windows / macOS / Linux 上支持 Mihomo / Clash Meta 配置的 Clash 客户端。TUN 网卡名由客户端或内核按系统选择，按需启用系统代理或 TUN；客户端覆写以实际运行配置为准。",
        ConfigTarget::Nikki => "路由器版：适用于 OpenClash、Nikki 等支持 Mihomo / Clash Meta 配置的插件。由插件管理路由、防火墙与 DNS 劫持，auto-route=false；请检查运行模式、局域网访问控制和覆写设置。控制接口仅本机监听，面板请通过受保护的管理通道访问。",
    };
    let exchange = if input.taiwan_node.is_some() {
        "\n交易所：在「台湾-中转」选择机场台湾节点；无匹配节点时拒绝连接。交易所组仅有台湾家宽和拒绝，不提供直连回退。访问 https://api4.ipify.org 验证台湾出口。参考域名清单不能覆盖未来所有新域名或硬编码 IP；请结合连接日志核对。"
    } else {
        ""
    };
    let media = "\nofiii：主站、播放器及指定 PC / 手机 / 电视 CDN 走「台湾影音」，默认机场台湾自动选择；已配置台湾家宽时可手动切换。台湾影音与交易所出口分开。";
    format!("{target}{exchange}{media}")
}

/// Text-only patches keep comments and YAML anchors intact.
pub fn apply_profile(yaml: String, input: &GenerateInput) -> String {
    let nikki = input.target == ConfigTarget::Nikki;
    let needs_hijack = !yaml.contains("dns-hijack:");
    let needs_proxy_dns = !yaml.contains("proxy-server-nameserver:");
    let mut out = format!(
        "# Ferry target: {}\n# Generated by Ferry {}; contains private credentials.\n",
        input.target.file_label(),
        env!("CARGO_PKG_VERSION")
    );
    let mut section = "";
    for line in yaml.lines() {
        if !line.is_empty() && !line.starts_with([' ', '#']) {
            section = line.split(':').next().unwrap_or("");
        }
        let patched = if line.starts_with("external-controller:") {
            "external-controller: 127.0.0.1:9090".to_string()
        } else if line.starts_with("secret:") {
            format!("secret: {}", yaml_dq(&input.controller_secret))
        } else if line.starts_with("allow-lan:") {
            format!("allow-lan: {nikki}")
        } else if section == "tun" && line.trim_start().starts_with("device:") {
            // Router managers can read/override a concrete generic device name.
            // Desktop kernels choose an OS-compatible default (utun on macOS).
            if nikki { "  device: Ferry".into() } else { continue; }
        } else if section == "tun" && line.trim_start().starts_with("stack:") {
            format!("  stack: {}", if nikki { "mixed" } else { "gvisor" })
        } else if section == "tun" && line.trim_start().starts_with("auto-route:") {
            format!("  auto-route: {}", !nikki)
        } else if section == "tun" && line.trim_start().starts_with("strict-route:") {
            format!("  strict-route: {}", !nikki)
        } else if section == "dns" && line.trim_start().starts_with("listen:") {
            format!(
                "  listen: {}:7874",
                if nikki { "0.0.0.0" } else { "127.0.0.1" }
            )
        } else if (nikki || input.taiwan_node.is_some())
            && (line.starts_with("ipv6:")
                || section == "dns" && line.trim_start().starts_with("ipv6:"))
        {
            if line.starts_with(' ') {
                "  ipv6: false".into()
            } else {
                "ipv6: false".into()
            }
        } else if section == "proxy-groups" {
            // Provider-only membership prevents a renamed residential proxy from
            // matching a region filter and recursively becoming its own upstream.
            line.replace("include-all: true", "include-all-providers: true")
        } else {
            line.to_string()
        };
        out.push_str(&patched);
        out.push('\n');
        if section == "tun" && line.trim_start().starts_with("enable:") && needs_hijack {
            out.push_str("  dns-hijack: [\"any:53\", \"tcp://any:53\"]\n");
        }
        if section == "dns" && line.trim_start().starts_with("enable:") && needs_proxy_dns {
            out.push_str("  proxy-server-nameserver: [223.5.5.5, 119.29.29.29]\n");
        }
    }
    out
}

/// Validate references and cycles, beyond merely accepting YAML syntax.
pub fn validate_graph(doc: &Value) -> Result<(), String> {
    let mut names: HashSet<String> = ["DIRECT", "REJECT", "REJECT-DROP", "PASS", "COMPATIBLE"]
        .into_iter()
        .map(str::to_string)
        .collect();
    let mut edges: HashMap<String, Vec<String>> = HashMap::new();
    for section in ["proxies", "proxy-groups"] {
        for item in doc[section].as_sequence().into_iter().flatten() {
            let name = item["name"]
                .as_str()
                .ok_or("节点 / 策略组名称必须为字符串。")?;
            if !names.insert(name.to_string()) {
                return Err(format!("节点 / 策略组名称重复或占用内置名称：{name}"));
            }
            let mut deps = Vec::new();
            if let Some(d) = item["dialer-proxy"].as_str() {
                deps.push(d.to_string());
            }
            for p in item["proxies"].as_sequence().into_iter().flatten() {
                deps.push(p.as_str().ok_or("策略组成员必须为字符串。")?.to_string());
            }
            edges.insert(name.to_string(), deps);
        }
    }
    for (name, deps) in &edges {
        for dep in deps {
            if !names.contains(dep) {
                return Err(format!("{name} 引用了不存在的节点 / 策略组：{dep}"));
            }
        }
    }
    fn visit(
        name: &str,
        edges: &HashMap<String, Vec<String>>,
        active: &mut HashSet<String>,
        done: &mut HashSet<String>,
    ) -> Result<(), String> {
        if done.contains(name) {
            return Ok(());
        }
        if !active.insert(name.into()) {
            return Err(format!("代理链存在循环引用：{name}"));
        }
        if let Some(deps) = edges.get(name) {
            for dep in deps {
                visit(dep, edges, active, done)?;
            }
        }
        active.remove(name);
        done.insert(name.into());
        Ok(())
    }
    let mut done = HashSet::new();
    for name in edges.keys() {
        visit(name, &edges, &mut HashSet::new(), &mut done)?;
    }
    Ok(())
}
